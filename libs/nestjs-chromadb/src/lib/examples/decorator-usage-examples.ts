function calculateRelevance(product: any, distance: number): string {
  const similarity = 1 - distance;
  if (similarity > 0.9) return 'excellent';
  if (similarity > 0.7) return 'good';
  if (similarity > 0.5) return 'fair';
  return 'poor';
}

function extractTags(content: string): string[] {
  // Simple tag extraction - in reality would use NLP
  const words = content.toLowerCase().split(/\s+/);
  return words.filter(word => word.length > 3 && !commonWords.includes(word));
}

function hashContent(content: string): string {
  // Simple hash for demonstration
  return Buffer.from(content).toString('base64').substring(0, 16);
}

function generateId(): string {
  return `${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
}

const commonWords = [
  'the', 'and', 'that', 'have', 'for', 'not', 'with', 'you', 'this', 'but',
  'his', 'from', 'they', 'she', 'her', 'been', 'than', 'its', 'would', 'there'
];

