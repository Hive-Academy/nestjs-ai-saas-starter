@Injectable()
@ChromaRepository({
  collection: 'agent_memories',
  autoEmbed: true,
  enableCaching: false, // Real-time memory updates
  enableValidation: true,
  autoTimestamp: true,
  enableSoftDelete: true, // Keep memory history
})
export class AgentMemoryRepository {
  constructor(private chromaService: ChromaDBService) {}

  /**
   * Store new memory with automatic relationship detection
   */
  @Profiled({
    category: 'memory_storage',
    logLevel: 'all',
    includeMemoryMetrics: true,
  })
  @Retry({
    maxAttempts: 2,
    strategy: 'fixed',
    baseDelay: 100,
  })
  async storeMemory(
    agentId: string,
    sessionId: string,
    content: string,
    memoryType: MemoryDocument['metadata']['memoryType'],
    importance = 5
  ): Promise<MemoryDocument> {
    // Find related memories for context linking
    const relatedMemories = await this.findRelatedMemories(content, agentId);

    const memory = await this.create({
      content,
      metadata: {
        agentId,
        sessionId,
        memoryType,
        importance,
        tags: extractTags(content),
        relatedMemories: relatedMemories.map(m => m.id),
      },
    });

    return memory;
  }

  /**
   * Retrieve contextual memories for agent decision making
   */
  @VectorQuery({
    collection: 'agent_memories',
    autoEmbed: true,
    defaultLimit: 10,
    includeDistances: true,
  })
  @Cached({
    ttl: 30000, // 30 seconds for fresh context
    keyGenerator: (agentId, context) => `context:${agentId}:${hashContent(context)}`,
  })
  @Profiled({
    slowQueryThreshold: 50, // Memory retrieval should be fast
    category: 'memory_retrieval',
  })
  async getContextualMemories(
    agentId: string,
    currentContext: string,
    maxAge?: number
  ) {
    const filters: any = {
      agentId,
      importance: { $gte: 3 }, // Only important memories
    };

    if (maxAge) {
      const cutoffDate = new Date(Date.now() - maxAge).toISOString();
      filters.createdAt = { $gte: cutoffDate };
    }

    return this.search(currentContext, {
      where: filters,
      limit: 10,
      threshold: 0.6,
    });
  }

  /**
   * Find related memories using vector similarity
   */
  @VectorQuery({
    collection: 'agent_memories',
    autoEmbed: true,
    defaultLimit: 5,
  })
  private async findRelatedMemories(
    content: string,
    agentId: string
  ): Promise<MemoryDocument[]> {
    return this.search(content, {
      where: { agentId },
      limit: 5,
      threshold: 0.8, // High similarity threshold
    });
  }

  /**
   * Memory consolidation - merge similar memories
   */
  @Profiled({
    category: 'memory_consolidation',
    logLevel: 'all',
  })
  async consolidateMemories(agentId: string, sessionId: string): Promise<void> {
    // Find memories for consolidation
    const sessionMemories = await this.findAll({
      where: { agentId, sessionId },
    });

    // Group similar memories and create consolidated versions
    const groups = await this.groupSimilarMemories(sessionMemories);

    for (const group of groups) {
      if (group.length > 1) {
        const consolidated = await this.createConsolidatedMemory(group);

        // Mark original memories as consolidated
        await this.updateMany(
          group.map(memory => ({
            id: memory.id,
            data: {
              metadata: {
                ...memory.metadata,
                consolidated: true,
                consolidatedInto: consolidated.id,
              },
            },
          }))
        );
      }
    }
  }

  private async groupSimilarMemories(
    memories: MemoryDocument[]
  ): Promise<MemoryDocument[][]> {
    // Implementation would use vector similarity to group memories
    // This is a simplified version
    return memories.reduce((groups: MemoryDocument[][], memory) => {
      // Find similar group or create new one
      return groups;
    }, []);
  }

  private async createConsolidatedMemory(
    memories: MemoryDocument[]
  ): Promise<MemoryDocument> {
    const consolidatedContent = memories
      .map(m => m.content)
      .join('\n\n--- CONSOLIDATED ---\n\n');

    const avgImportance = Math.round(
      memories.reduce((sum, m) => sum + m.metadata.importance, 0) / memories.length
    );

    return this.create({
      content: consolidatedContent,
      metadata: {
        agentId: memories[0].metadata.agentId,
        sessionId: memories[0].metadata.sessionId,
        memoryType: 'context',
        importance: Math.min(10, avgImportance + 1), // Boost consolidated importance
        tags: [...new Set(memories.flatMap(m => m.metadata.tags))],
        relatedMemories: memories.map(m => m.id),
      },
    });
  }
}

