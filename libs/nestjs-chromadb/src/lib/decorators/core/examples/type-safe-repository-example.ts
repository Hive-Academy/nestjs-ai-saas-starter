/**
 * User document with strongly typed metadata
 */
interface UserDocument extends BaseDocument<{
  readonly name: string;
  readonly email: string;
  readonly age: number;
  readonly role: 'user' | 'admin' | 'moderator';
  readonly tags: readonly string[];
  readonly isActive: boolean;
  readonly joinedAt: string;
  readonly lastLoginAt?: string;
}> {}

/**
 * Product document with strongly typed metadata
 */
interface ProductDocument extends BaseDocument<{
  readonly title: string;
  readonly description: string;
  readonly price: number;
  readonly category: string;
  readonly inStock: boolean;
  readonly tags: readonly string[];
  readonly rating: number;
  readonly reviewCount: number;
}> {}

