@Injectable()
@ChromaRepository<ProductDocument>({
  collection: 'products',
  autoEmbed: true,
  enableCaching: true,
  enableValidation: true,
  autoTimestamp: true,
  defaultBatchSize: 50,
  errorHandling: 'log_and_continue',
})
export class ProductRepository {
  private readonly logger = new Logger(ProductRepository.name);

  constructor(
    private readonly chromaService: ChromaDBService
  ) {}

  /**
   * Find products by category with price filtering
   */
  async findProductsByCategory(
    category: string,
    priceRange?: { min?: number; max?: number }
  ): Promise<ProductDocument[]> {
    const whereClause: Record<string, unknown> = { category };

    if (priceRange) {
      if (priceRange.min !== undefined) {
        whereClause.price = { ...whereClause.price as object, $gte: priceRange.min };
      }
      if (priceRange.max !== undefined) {
        whereClause.price = { ...whereClause.price as object, $lte: priceRange.max };
      }
    }

    return await this.findAll({ where: whereClause });
  }

  /**
   * Search products with semantic similarity and metadata filters
   */
  async searchProducts(query: string, filters: {
    category?: string;
    inStock?: boolean;
    minRating?: number;
    maxPrice?: number;
  } = {}): Promise<Array<{ product: ProductDocument; score: number }>> {
    const whereClause: Record<string, unknown> = {};

    if (filters.category) {
      whereClause.category = filters.category;
    }

    if (typeof filters.inStock === 'boolean') {
      whereClause.inStock = filters.inStock;
    }

    if (typeof filters.minRating === 'number') {
      whereClause.rating = { $gte: filters.minRating };
    }

    if (typeof filters.maxPrice === 'number') {
      whereClause.price = { 
        ...whereClause.price as object, 
        $lte: filters.maxPrice 
      };
    }

    return await this.searchWithScores(query, {
      where: whereClause,
      limit: 20,
      include: {
        metadata: true,
        documents: true,
        distances: true,
      }
    });
  }
}

