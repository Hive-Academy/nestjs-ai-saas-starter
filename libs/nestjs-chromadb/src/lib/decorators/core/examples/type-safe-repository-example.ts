@Injectable()
export class UserManagementService {
  constructor(
    private readonly userRepository: UserRepository,
    private readonly logger: Logger
  ) {}

  /**
   * Register new user with comprehensive validation
   */
  async registerUser(registrationData: {
    name: string;
    email: string;
    age: number;
  }): Promise<UserDocument> {
    try {
      return await this.userRepository.createUserSafely({
        ...registrationData,
        role: 'user',
        content: `Welcome ${registrationData.name}! Your profile is ready.`,
      });
    } catch (error) {
      this.logger.error('User registration failed', error);
      throw new Error(`Registration failed: ${error instanceof Error ? error.message : 'Unknown error'}`);
    }
  }

  /**
   * Find users with advanced search capabilities
   */
  async searchUsers(query: string, filters: {
    role?: UserDocument['metadata']['role'];
    minAge?: number;
    isActive?: boolean;
  } = {}): Promise<UserDocument[]> {
    let users: UserDocument[] = [];

    if (filters.role) {
      users = await this.userRepository.findUsersByRole(filters.role, query);
    } else {
      users = await this.userRepository.search(query, { limit: 50 });
    }

    // Apply additional filters
    if (filters.minAge !== undefined || filters.isActive !== undefined) {
      users = users.filter(user => {
        if (filters.minAge !== undefined && user.metadata.age < filters.minAge) {
          return false;
        }
        if (filters.isActive !== undefined && user.metadata.isActive !== filters.isActive) {
          return false;
        }
        return true;
      });
    }

    return users;
  }

  /**
   * Get user statistics with type safety
   */
  async getUserStatistics(): Promise<{
    total: number;
    byRole: Record<UserDocument['metadata']['role'], number>;
    averageAge: number;
    activeUsers: number;
  }> {
    const allUsers = await this.userRepository.findAll();

    const stats = {
      total: allUsers.length,
      byRole: {
        user: 0,
        admin: 0,
        moderator: 0,
      } as Record<UserDocument['metadata']['role'], number>,
      averageAge: 0,
      activeUsers: 0,
    };

    let totalAge = 0;

    for (const user of allUsers) {
      // Type-safe access to metadata
      stats.byRole[user.metadata.role]++;
      totalAge += user.metadata.age;
      
      if (user.metadata.isActive) {
        stats.activeUsers++;
      }
    }

    stats.averageAge = allUsers.length > 0 ? totalAge / allUsers.length : 0;

    return stats;
  }
}

