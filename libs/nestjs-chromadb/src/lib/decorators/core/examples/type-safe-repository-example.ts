/**
 * Type safety validation example
 */
export function demonstrateTypeValidation(): void {
  // ✅ Valid document
  const validUser: UserDocument = {
    id: 'user-123',
    content: 'User profile content',
    metadata: {
      name: 'Jane Doe',
      email: 'jane@example.com',
      age: 25,
      role: 'user',
      tags: ['developer', 'typescript'],
      isActive: true,
      joinedAt: '2024-01-01T00:00:00Z',
    }
  };

  console.log('Valid user document:', isValidBaseDocument<UserDocument>(validUser));

  // ❌ Invalid document (missing required fields)
  const invalidDocument = {
    id: 'invalid-123',
    // missing content
    metadata: {
      name: 'Invalid User',
      // missing email and other required fields
    }
  };

  console.log('Invalid document:', isValidBaseDocument<UserDocument>(invalidDocument));

  // ✅ Safe conversion
  const safeUser = TypeSafeConverter.toDocument<UserDocument>(validUser);
  console.log('Safe conversion result:', safeUser?.id);

  const unsafeUser = TypeSafeConverter.toDocument<UserDocument>(invalidDocument);
  console.log('Unsafe conversion result:', unsafeUser); // Should be null
}