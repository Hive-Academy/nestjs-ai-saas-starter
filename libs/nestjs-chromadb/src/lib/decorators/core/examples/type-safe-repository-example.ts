// 2. Type-Safe Repository Implementation
// =====================================================================

/**
 * Type-safe user repository with enhanced validation
 */
@Injectable()
@ChromaRepository<UserDocument>({
  collection: 'users',
  autoEmbed: true,
  enableCaching: true,
  enableValidation: true,
  autoTimestamp: true,
  autoGenerateIds: true,
  enableSoftDelete: false,
  errorHandling: 'throw',
})
export class UserRepository {
  private readonly logger = new Logger(UserRepository.name);

  constructor(
    private readonly chromaService: ChromaDBService
  ) {}

  // All CRUD methods are auto-generated by the decorator with full type safety

  /**
   * Custom method: Find users by email with type validation
   */
  @TypeSafeMethod<[string, RepositoryOperationOptions?], Promise<UserDocument | null>>(
    ([email, options]) => {
      if (typeof email !== 'string' || email.length === 0) {
        throw new Error('Email must be a non-empty string');
      }
    }
  )
  async findByEmail(email: string, options?: RepositoryOperationOptions): Promise<UserDocument | null> {
    const users = await this.findAll({ 
      where: { email },
      ...options 
    });

    const user = users[0] || null;
    
    // Type-safe validation
    if (user && !isValidBaseDocument<UserDocument>(user)) {
      this.logger.error('Retrieved user document failed type validation');
      return null;
    }

    return user;
  }

  /**
   * Custom method: Find adult users with type constraints
   */
  async findAdultUsers(minAge: number = 18): Promise<UserDocument[]> {
    // Input validation
    if (typeof minAge !== 'number' || minAge < 0 || minAge > 150) {
      throw new Error('Invalid age constraint');
    }

    const users = await this.findAll({
      where: { age: { $gte: minAge } }
    });

    // Type-safe conversion
    return TypeSafeConverter.toDocumentArray<UserDocument>(users, true);
  }

  /**
   * Custom method: Search users by role with type safety
   */
  async findUsersByRole(
    role: UserDocument['metadata']['role'],
    searchQuery?: string,
    options: RepositorySearchOptions = {}
  ): Promise<UserDocument[]> {
    // Validate role enum
    const validRoles: UserDocument['metadata']['role'][] = ['user', 'admin', 'moderator'];
    if (!validRoles.includes(role)) {
      throw new Error(`Invalid role: ${role}. Must be one of: ${validRoles.join(', ')}`);
    }

    if (searchQuery) {
      // Vector search with metadata filter
      return await this.search(searchQuery, {
        where: { role },
        limit: options.limit || 20,
        ...options
      });
    } else {
      // Metadata filter only
      return await this.findAll({
        where: { role },
        ...options
      });
    }
  }

  /**
   * Custom method: Create user with comprehensive validation
   */
  async createUserSafely(userData: {
    name: string;
    email: string;
    age: number;
    role: UserDocument['metadata']['role'];
    content?: string;
  }): Promise<UserDocument> {
    // Input validation
    if (!userData.name || userData.name.trim().length === 0) {
      throw new Error('Name is required');
    }

    if (!userData.email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(userData.email)) {
      throw new Error('Valid email is required');
    }

    if (typeof userData.age !== 'number' || userData.age < 0 || userData.age > 150) {
      throw new Error('Age must be between 0 and 150');
    }

    // Check if user already exists
    const existingUser = await this.findByEmail(userData.email);
    if (existingUser) {
      throw new Error(`User with email ${userData.email} already exists`);
    }

    // Create user document with type safety
    const userDocument: Omit<UserDocument, 'id'> = {
      content: userData.content || `User profile for ${userData.name}`,
      metadata: {
        name: userData.name,
        email: userData.email,
        age: userData.age,
        role: userData.role,
        tags: [],
        isActive: true,
        joinedAt: new Date().toISOString(),
      }
    };

    // Validate document structure before creation
    const tempDoc = { ...userDocument, id: 'temp' } as UserDocument;
    assertValidDocument<UserDocument>(tempDoc, 'user document');

    return await this.create(userDocument);
  }

  /**
   * Custom method: Bulk update users with type safety
   */
  async updateUsersLastLogin(userIds: string[]): Promise<void> {
    if (!Array.isArray(userIds) || userIds.length === 0) {
      throw new Error('User IDs array is required');
    }

    const updates = userIds.map(id => ({
      id,
      data: {
        metadata: {
          lastLoginAt: new Date().toISOString()
        }
      } as Partial<UserDocument>
    }));

    const result = await this.updateMany(updates);
    
    if (!result.success) {
      throw new Error(`Failed to update users: ${result.errors?.join(', ')}`);
    }

    this.logger.log(`Updated last login for ${result.documentsProcessed} users`);
  }
}

